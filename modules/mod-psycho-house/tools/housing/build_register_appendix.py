#!/usr/bin/env python3
"""Emit the full town centre stock register - every vendor, every line.

    python3 tools/housing/build_register_appendix.py

Doc 09 is written by hand and carries the analysis. This script writes the part that is
not analysis: one table per vendor with every captured stock line, its price, its currency
and the retail item id where one has been resolved. A line with no id yet says so instead
of being left out.

Output: generated/town-center-full-stock.md
"""

import collections
import csv
import os

HERE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(HERE, "data")
OUT = os.path.join(HERE, "generated", "town-center-full-stock.md")


def read(name):
    with open(os.path.join(DATA, name), newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def cell(text):
    return text.replace("|", "\\|").strip() or "-"


def main():
    vendors = read("vendor_npc_ids.csv")
    stock = read("town-center-stock.csv")
    items = read("town-center-items.csv")

    ids = {}
    for row in items:
        key = (row["vendor"], row["item_name"])
        if row["item_id"].strip():
            ids[key] = row["item_id"].strip()

    by_vendor = collections.OrderedDict()
    for row in stock:
        by_vendor.setdefault(row["vendor"], []).append(row)

    order = sorted(by_vendor, key=lambda name: (-len(by_vendor[name]), name))
    catalogue = {row["vendor"]: row for row in vendors}
    npc = {row["vendor"]: row for row in vendors}

    lines = []
    lines.append("# Full town centre stock register")
    lines.append("")
    lines.append("Generated by `tools/housing/build_register_appendix.py` - do not edit by hand.")
    lines.append("One table per vendor, every captured stock line in it. The retail id column")
    lines.append("is filled where the id was read off a Wowhead listing and is `-` where it")
    lines.append("has not been resolved yet, so a missing id is visible rather than absent.")
    lines.append("")

    total_captured = sum(len(rows) for rows in by_vendor.values())
    total_catalogue = sum(int(row["items"]) for row in vendors)
    total_ids = len(ids)
    no_price = sum(1 for row in stock if not row["price"].strip())
    missing_ids = total_captured - sum(1 for row in stock
                                       if (row["vendor"], row["item"]) in ids)
    lines.append("| Figure | Count |")
    lines.append("| --- | --- |")
    lines.append("| Vendors in the register | {} |".format(len(vendors)))
    lines.append("| Catalogue items across those vendors | {} |".format(total_catalogue))
    lines.append("| Stock lines captured | {} |".format(total_captured))
    lines.append("| Stock lines with a retail item id | {} |".format(total_captured - missing_ids))
    lines.append("| Stock lines without an id yet | {} |".format(missing_ids))
    lines.append("| Stock lines with no published price | {} |".format(no_price))
    lines.append("")

    for name in order:
        rows = by_vendor[name]
        entry = npc.get(name, {})
        have = sum(1 for row in rows if (row["vendor"], row["item"]) in ids)
        lines.append("## {}".format(name))
        lines.append("")
        lines.append("npc {}, {} catalogue items, {} captured, {} with an id.".format(
            entry.get("npc_id", "unknown"), entry.get("items", len(rows)),
            len(rows), have))
        lines.append("")
        lines.append("| Item | Price | Currency | Retail id | Note |")
        lines.append("| --- | --- | --- | --- | --- |")
        for row in rows:
            item_id = ids.get((row["vendor"], row["item"]), "-")
            price = row["price"].strip() or "not published"
            lines.append("| {} | {} | {} | {} | {} |".format(
                cell(row["item"]), cell(price), cell(row["currency"] or "-"),
                item_id, cell(row["note"] or "")))
        lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines).rstrip() + "\n")
    print("wrote {} lines, {} vendors, {} stock lines, {} with ids".format(
        len(lines), len(order), total_captured, total_captured - missing_ids))


if __name__ == "__main__":
    main()
