def category(name):
    low = name.lower()
    for cat, keys in CATEGORY_RULES:
        for k in keys:
            if k in low:
                return cat
    return "Accents"


def budget(price):
    try:
        p = int(price)
    except (TypeError, ValueError):
        return 1
    if p <= 25:
        return 1
    if p <= 75:
        return 3
    return 5


def sql_escape(text):
    return text.replace("\\", "\\\\").replace("'", "''")


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def read_schema_parts():
    """Split the base world file into (schema + biomes + plots, amenities + names)."""
    with open(BASE_SQL, encoding="utf-8") as fh:
        text = fh.read()
    head, rest = text.split("-- ---------------------------------------------------------------------------\n-- Vendors.", 1)
    tail = rest.split("-- ---------------------------------------------------------------------------\n-- Amenities.", 1)[1]
    tail = tail.split("-- ---------------------------------------------------------------------------\n-- Decor catalogue", 1)[0]
    return head, "-- Amenities." + tail


def write(path, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)


def copy_core(draft):
    for part in ("game", "scripts"):
        src = os.path.join(SRC, part)
        dst = os.path.join(DRAFTS, draft, "src", part)
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        shutil.copytree(src, dst)
    for folder in ("addon",):
        src = os.path.join(ROOT, folder)
        dst = os.path.join(DRAFTS, draft, folder)
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        shutil.copytree(src, dst)


def build_midnight():
    draft = "midnight-port"
    schema, world = read_schema_parts()
    write(os.path.join(DRAFTS, draft, "sql", "world", "01_schema.sql"), BANNER + schema)
    write(os.path.join(DRAFTS, draft, "sql", "world", "02_world_content.sql"), BANNER + world)
    os.makedirs(os.path.join(DRAFTS, draft, "sql", "characters"), exist_ok=True)
    shutil.copyfile(CHAR_SQL, os.path.join(DRAFTS, draft, "sql", "characters",
                                           "01_characters_schema.sql"))

    stock = read_csv(os.path.join(DATA, "town-center-stock.csv"))
    go_map = {}
    go_path = os.path.join(DATA, "town-center-go-map.csv")
    if os.path.exists(go_path):
        for row in read_csv(go_path):
            go_map[row["item"]] = (row["gameobject_entry"], row["go_constant"],
                                   row["confidence"])
    items = read_csv(os.path.join(DATA, "town-center-items.csv"))
    npcs = read_csv(os.path.join(DATA, "vendor_npc_ids.csv"))

    ids = {}
    for row in npcs:
        if row["npc_id"]:
            ids[row["vendor"]] = row["npc_id"]

    item_price_by_name = {}
    for row in items:
        if row["price"].strip():
            item_price_by_name.setdefault(row["item_name"], row["price"].strip())
    item_id_by_name = {}
    for row in items:
        item_id_by_name.setdefault(row["item_name"], row["item_id"])

    # One decor row per (name, price, currency); stock rows point at it.
    decor_key = {}
    decor_rows = []
    stock_rows = []
    unpriced = {}
    vendor_ids = {}
    vendor_order = sorted({r["vendor"] for r in stock},
                          key=lambda v: (v.lower().replace('"', "").strip()))
    for name in sorted((r["vendor"] for r in npcs), key=lambda v: v.lower().replace('"', "").strip()):
        if name not in vendor_order:
            vendor_order.append(name)
    for idx, vendor in enumerate(vendor_order):
        vendor_ids[vendor] = 101 + idx

    for row in stock:
        vendor = row["vendor"]
        if vendor not in vendor_ids:
            print("stock row for unknown vendor", vendor, file=sys.stderr)
            continue
        cur = row["currency"].strip()
        if cur == "Community Coupons":
            currency = 3363
        elif cur == "Tricky Treat":
            currency = 33226  # item cost, not a currency id
        else:
            currency = 0
        price = row["price"].strip()
        if not price:
            price = item_price_by_name.get(row["item"], "")
            unpriced.setdefault(vendor, []).append(row["item"])
            continue
        key = (row["item"], price, currency)
        if key not in decor_key:
            decor_key[key] = 1000 + len(decor_rows)
            go_entry = go_map.get(row["item"], ("0", "", "none"))[0]
            decor_rows.append({
                "id": decor_key[key],
                "name": row["item"],
                "go": go_entry,
                "item": item_id_by_name.get(row["item"], "0"),
                "budget": budget(price),
                "category": category(row["item"]),
                "source": vendor_ids[vendor],
                # The two neighbourhoods are faction hubs: Razorwind Shores is Horde,
                # Founder's Point is Alliance. A piece both hubs sell is two rows at two
                # prices, and the mask is what keeps the cheaper one out of the other
                # faction's shop - HousingMgr::BuyDecor refuses a piece whose mask does not
                # carry the buyer's bit, and the shop listing filters the same way.
                "faction": 2 if vendor in HORDE_VENDORS else 1,
                "price": price,
                "currency": currency,
                "note": row["note"],
            })
        stock_rows.append((vendor_ids[vendor], decor_key[key], price))

    # The vendor comment states how many stock lines the file actually inserts, not how many
    # the vendor page listed. Four comments used to promise a line that was not there - one
    # vendor promised sixteen and shipped none - because the count was taken before the
    # unpriced rows were dropped.
    priced = {}
    for row in stock_rows:
        priced[row[0]] = priced.get(row[0], 0) + 1

    vendors_sql = ["DELETE FROM `housing_vendor` WHERE `id` BETWEEN 101 AND 199;",
                   "INSERT INTO `housing_vendor` (`id`, `name`, `biome_id`, `role`, `creature_entry`, `retail_name`, `comment`) VALUES"]
    vlines = []
    for vendor in vendor_order:
        role = 4 if vendor in PET_VENDORS else (5 if vendor in HOLIDAY_VENDORS else 0)
        faction = "Horde, Razorwind Shores" if vendor in HORDE_VENDORS else "Alliance, Founder's Point"
        npc = ids.get(vendor, "0")
        captured = sum(1 for r in stock if r["vendor"] == vendor)
        shipped = priced.get(vendor_ids[vendor], 0)
        if shipped == captured:
            comment = "npc {}, {}, {} stock lines".format(npc, faction, shipped)
        else:
            comment = "npc {}, {}, {} of {} stock lines priced".format(
                npc, faction, shipped, captured)
        vlines.append("({}, '{}', 0, {}, 0, '{}', '{}')".format(
            vendor_ids[vendor], sql_escape(vendor), role, sql_escape(vendor),
            sql_escape(comment)))
    vendors_sql.append(",\n".join(vlines) + ";")

    decor_sql = ["DELETE FROM `housing_decor` WHERE `id` BETWEEN 1000 AND 1999;",
                 "INSERT INTO `housing_decor` (`id`, `name`, `gameobject_entry`, `item_entry`, `budget_cost`, `surface`, `placement`, `category`, `source_type`, `source_id`, `price`, `currency`, `faction_mask`, `scale_min`, `scale_max`, `flags`) VALUES"]
    dlines = []
    for d in decor_rows:
        dlines.append("({}, '{}', {}, {}, {}, {}, 2, '{}', 0, {}, {}, {}, {}, 0.5, 3, 0)".format(
            d["id"], sql_escape(d["name"]), d["go"], d["item"], d["budget"],
            surface_band(d["category"]), d["category"],
            d["source"], d["price"], d["currency"], d["faction"]))
    decor_sql.append(",\n".join(dlines) + ";")
    decor_sql.append("\n-- gameobject_entry is a real 8.3.7 game object chosen by tools/housing/map_decor_go.py.")
    decor_sql.append("-- Provenance per piece is in data/town-center-go-map.csv; a 0 here means no")
    decor_sql.append("-- candidate existed and the row stays flagged DecorFlagUnmapped at load.")
    decor_sql.append("-- item_entry holds the Midnight decor item id where it is known ({} of {}).".format(
        sum(1 for d in decor_rows if d["item"] != "0"), len(decor_rows)))

    stock_sql = ["DELETE FROM `housing_vendor_stock` WHERE `vendor_id` BETWEEN 101 AND 199;",
                 "INSERT INTO `housing_vendor_stock` (`vendor_id`, `decor_id`, `price`) VALUES"]
    stock_sql.append(",\n".join("({}, {}, {})".format(*s) for s in stock_rows) + ";")
    if unpriced:
        stock_sql.append("\n\n-- Unpriced on the vendor page, deliberately not inserted so they do not")
        stock_sql.append("-- come out free. Fill the price from the vendor and re-run this tool:")
        for vendor in sorted(unpriced):
            stock_sql.append("--   vendor {} (id {}): {}".format(
                vendor, vendor_ids.get(vendor, 0), ", ".join(sorted(unpriced[vendor]))))

    write(os.path.join(DRAFTS, draft, "sql", "world", "03_vendors_retail.sql"),
          BANNER + "\n".join(vendors_sql) + "\n")
    write(os.path.join(DRAFTS, draft, "sql", "world", "04_decor_retail.sql"),
          BANNER + "\n".join(decor_sql) + "\n")
    write(os.path.join(DRAFTS, draft, "sql", "world", "05_stock_retail.sql"),
          BANNER + "\n".join(stock_sql) + "\n")
    print("midnight-port: {} vendors, {} decor, {} stock".format(
        len(vendor_order), len(decor_rows), len(stock_rows)))
    copy_core(draft)


SMALL_WORDS = {"of", "the", "and", "for", "in", "on", "with", "to"}


def humanise(constant):
    """Turn GO_SOME_NAME_2 into a readable placeholder name.

    The runtime UPDATE copies the real name out of gameobject_template, so this is only
    what the SQL reads like before the module has loaded once.
    """
    words = constant
    for prefix in ("GO_", "OBJECT_", "GAMEOBJECT_"):
        if words.startswith(prefix):
            words = words[len(prefix):]
    words = re.sub(r"([A-Za-z])(\d+)$", r"\1_\2", words)
    parts = [w for w in words.split("_") if w]
    out = []
    for i, word in enumerate(parts):
        low = word.lower()
        if low.isdigit():
            out.append(low)
        elif i and low in SMALL_WORDS:
            out.append(low)
        else:
            out.append(low.capitalize())
    return " ".join(out) or constant


def build_native():
    draft = "bfa-native"
    schema, world = read_schema_parts()
    write(os.path.join(DRAFTS, draft, "sql", "world", "01_schema.sql"), BANNER + schema)
    write(os.path.join(DRAFTS, draft, "sql", "world", "02_world_content.sql"), BANNER + world)
    os.makedirs(os.path.join(DRAFTS, draft, "sql", "characters"), exist_ok=True)
    shutil.copyfile(CHAR_SQL, os.path.join(DRAFTS, draft, "sql", "characters",
                                           "01_characters_schema.sql"))

    index = read_csv(os.path.join(GEN, "source-asset-index.csv"))
    gos = [r for r in index if r["kind"] == "gameobject" and r["decor"] == "yes"]
    reject = ("DOOR", "GATE", "TRAP", "TRIGGER", "PORTAL", "INSTANCE", "CORPSE",
              "SPAWN", "SOUND", "SPELL", "AURA", "DUMMY", "BOSS", "GOSSIP",
              "MARKER", "EXPLOSION", "MISSILE", "PROJECTILE", "GRAVEYARD", "ZONE",
              "BARRIER", "INVISIBLE", "ARENA", "CORPSE", "QUEST", "WAYPOINT",
              "FLIGHT", "TEMPLE_DOOR", "SMOKE", "FOG", "LIGHT_BEAM")
    seen = {}
    for row in gos:
        entry = row["entry"]
        label = row["constant"] or row["name"]
        name = label.upper()
        if not name or any(bad in name for bad in reject):
            continue
        if entry in seen:
            continue
        seen[entry] = row
    rows = sorted(seen.values(), key=lambda r: int(r["entry"]))
    print("native: {} decor rows from {}".format(len(rows), "generated/source-asset-index.csv"))

    vendors = [("Housing Steward", 0, 2), ("Groundskeeper", 0, 0),
               ("Stonewright", 0, 0), ("Lamplighter", 0, 0),
               ("Stores Overseer", 0, 0), ("Pet Handler", 0, 4),
               ("Tradesman", 0, 0), ("Festival Steward", 0, 5)]
    vsql = ["DELETE FROM `housing_vendor` WHERE `id` BETWEEN 201 AND 208;",
            "INSERT INTO `housing_vendor` (`id`, `name`, `biome_id`, `role`, `creature_entry`, `retail_name`, `comment`) VALUES"]
    vlines = []
    for i, (name, biome, role) in enumerate(vendors):
        vlines.append("({}, '{}', {}, {}, 0, NULL, 'bind creature_entry with tools/sql/bind_native_vendors.sql')".format(
            201 + i, name, biome, role))
    vsql.append(",\n".join(vlines) + ";")

    dsql = ["DELETE FROM `housing_decor` WHERE `id` BETWEEN 2000 AND 2999;",
            "INSERT INTO `housing_decor` (`id`, `name`, `gameobject_entry`, `budget_cost`, `surface`, `placement`, `category`, `source_type`, `source_id`, `price`, `currency`, `faction_mask`, `scale_min`, `scale_max`, `flags`) VALUES"]
    dlines = []
    ssql_lines = []
    for i, row in enumerate(rows):
        entry = int(row["entry"])
        label = row["constant"] or row["name"]
        cat = category(label.replace("_", " ").lower())
        label = humanise(label)
        price = NATIVE_PRICE.get(cat, 10)
        vendor = 201 + (entry % len(vendors))
        dlines.append("({}, '{}', {}, {}, {}, 2, '{}', 0, {}, {}, 0, 3, 0.5, 3, 0)".format(
            2000 + i, sql_escape(label), entry, budget(price), surface_band(cat),
            cat, vendor, price))
        ssql_lines.append("({}, {}, {})".format(vendor, 2000 + i, price))
    dsql.append(",\n".join(dlines) + ";")
    dsql.append("\n-- Display names come from the world DB, not from the constant name:")
    dsql.append("UPDATE `housing_decor` hd JOIN `gameobject_template` gt")
    dsql.append("  ON gt.`entry` = hd.`gameobject_entry`")
    dsql.append("SET hd.`name` = gt.`name`")
    dsql.append("WHERE hd.`id` BETWEEN 2000 AND 2999 AND gt.`name` <> '';")

    ssql = ["DELETE FROM `housing_vendor_stock` WHERE `vendor_id` BETWEEN 201 AND 208;",
            "INSERT INTO `housing_vendor_stock` (`vendor_id`, `decor_id`, `price`) VALUES"]
    ssql.append(",\n".join(ssql_lines) + ";")

    write(os.path.join(DRAFTS, draft, "sql", "world", "03_decor_native.sql"),
          BANNER + "\n".join(dsql) + "\n")
    write(os.path.join(DRAFTS, draft, "sql", "world", "04_vendors_native.sql"),
          BANNER + "\n".join(vsql) + "\n" + "\n".join(ssql) + "\n")
    copy_core(draft)


def main():
    build_midnight()
    build_native()


if __name__ == "__main__":
    main()
