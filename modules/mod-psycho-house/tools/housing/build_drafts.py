#!/usr/bin/env python3
"""Build the two draft modules from the captured data.

  drafts/midnight-port   - retail content: 38 vendors, 675 stock lines, 201 item ids
  drafts/bfa-native      - only ids that already exist in the 8.3.7 tree

Both drafts share the same C++ core and the same schema. They differ in the content
files (vendors, decor catalogue, prices) and in the conf defaults.

Run from the housing folder:

    python3 tools/housing/build_drafts.py

Re-running is safe: every generated file is rewritten from the CSVs, and the generated
files are marked with a header so they are never edited by hand.
"""

