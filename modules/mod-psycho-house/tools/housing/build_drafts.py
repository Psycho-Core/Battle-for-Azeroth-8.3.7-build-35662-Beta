# Surface bands, shared by both drafts so the same category means the same thing in both.
# HousingDefines.h: 0 floor, 1 wall, 2 ceiling, 3 any. Only two answers are unambiguous from
# a catalogue: a rug, a chair, a bed, a crate and a plant stand on the floor, and wall art
# hangs on a wall. Everything else - a lantern that could be a sconce or a chandelier, a fence
# that could be a yard fence or a balcony rail, a gift box - is SurfaceAny, because a band
# that guesses wrong locks a player out of placing the piece instead of letting them decide.
SURFACE_FLOOR = 0
SURFACE_WALL = 1
SURFACE_ANY = 3
SURFACE_BANDS = {
    "Rugs": SURFACE_FLOOR,
    "Tables": SURFACE_FLOOR,
    "Beds": SURFACE_FLOOR,
    "Seating": SURFACE_FLOOR,
    "Storage": SURFACE_FLOOR,
    "Books": SURFACE_FLOOR,
    "Pets": SURFACE_FLOOR,
    "Nature": SURFACE_FLOOR,
    "Wall Art": SURFACE_WALL,
    "Lighting": SURFACE_ANY,
    "Structural": SURFACE_ANY,
    "Holiday": SURFACE_ANY,
    "Accents": SURFACE_ANY,
}


def surface_band(category_name):
    """Category string as written in SQL is quoted; strip it before the lookup."""
    return SURFACE_BANDS.get(category_name.strip("'"), SURFACE_ANY)


