BANNER = ("-- Generated by tools/housing/build_drafts.py - do not edit by hand.\n"
          "-- Source data: data/town-center-stock.csv, data/town-center-items.csv,\n"
          "--              data/vendor_npc_ids.csv, generated/source-asset-index.csv\n\n")

