#!/usr/bin/env python3
"""Write the ten riddle treasure hunts into both drafts.

    python3 tools/housing/build_hunts.py

One file per draft, `sql/world/08_hunts.sql`, carrying four things:

  housing_decor      the ten reward pieces, ids 1900-1909 in draft A and 2900-2909 in
                     draft B, source type 4 (treasure hunt) and source id = the hunt
  housing_hunt       the ten rows: riddle, quest, reward, cache, faction mask
  quest_template     the ten quests, 900110-900119, in the module's reserved range
  quest_objectives   one gameobject objective per quest, the cache it points at

Every game object entry below is a real 8.3.7 entry taken from the source asset index, and
every one of them is checked against that index by check_coverage.py. The reward piece is a
`housing_decor` row rather than an item, so a hunt needs no `item_template` row: the piece
goes into the account's collection, which is what gates placing it.

The piece is named after the object it is made of, not after the retail guide entry it stands
in for. A piece called "Wine Vat" whose object is an idol is the thing this file exists to
avoid, so the ten names are the ten objects: a keg, an iron tomb, a cluster display, three
braziers, a keg trap, a banner, a fire, and two crates. The riddle still carries the retail
site, and draft 04's table says which object stands behind which name.

The reward for a hunt is the same object in both drafts. Draft A's retail catalogue has a
Founder's Point piece that fits each riddle, but draft B's catalogue is built from the
native set and has no equivalents, so both drafts get authored rows instead of borrowing
an existing one - a hunt that rewards nothing on one of the two drafts is worse than a
reward that is a hand-picked object on both.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DRAFTS = os.path.join(HERE, "drafts")

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_quests  # noqa: E402  the quest column list and quoting rule live there

# id, name, riddle, reward label, reward game object, cache label, cache game object
HUNTS = [
    (1, "The Beer Garden Cache",
     "Where the beer flows and the wheel turns.",
     "Bar Keg", 170607, "Suspicious Crate", 190094),
    (2, "The Graveyard Cache",
     "The stone remembers the names.",
     "Iron Gravestone", 220864, "Crate of Cellblock Rations", 206996),
    (3, "The Mushroom Ring Cache",
     "Under the ring of caps.",
     "Blue Cluster Display", 7364, "Stout Crate of Mantid", 221802),
    (4, "The Lighthouse Cache",
     "The eye that never blinks.",
     "Harbour Brazier", 195424, "Massive Crate of Mogu", 221803),
    (5, "The Stomping Vat Cache",
     "Grapes trodden, promises kept.",
     "Wine Keg", 171941, "Massive Crate of Mantid", 221804),
    (6, "The Aerie Cache",
     "Where gryphons sleep.",
     "Aerie Banner", 178205, "Lightweight Crate of Mantid", 221806),
    (7, "The Ridge Cache",
     "The bridge that only one house crosses.",
     "Ridge Fire", 177417, "Lightweight Crate of Mogu", 221807),
    (8, "The Breakwater Cache",
     "Salt in the timbers.",
     "Smuggler's Crate", 190094, "Lightweight Crate of Mantid 2", 221808),
    (9, "The Notice Board Cache",
     "Beneath the notice of neighbours.",
     "Plagued Crate", 190095, "Lightweight Crate of Mantid 3", 221809),
    (10, "The Cliff Cache",
     "The lamp the wind cannot kill.",
     "Storm Brazier", 195403, "Cache of Storms", 194312),
]

QUEST_FIRST = 900110
OBJECTIVE_FIRST = 9001100
HUNT_FIRST_QUEST = QUEST_FIRST

DECOR_RANGES = {"midnight-port": 1900, "bfa-native": 2900}

HUNT_COLUMNS = ("id", "name", "riddle", "quest_id", "reward_decor", "cache_entry",
                "x", "y", "z", "faction_mask")

HEADER = """-- Generated by tools/housing/build_hunts.py - do not edit by hand.
--
-- The ten riddle treasure hunts: the reward pieces, the hunt rows, the quests and the
-- gameobject objectives. Ids 1900-1909 (draft A) and 2900-2909 (draft B) are the reward
-- pieces; 900110-900119 are the quests, inside the module's reserved range.
--
-- Every game object entry here is a real 8.3.7 entry from the source asset index. The
-- caches are crates and storm caches; the rewards are a keg, a tomb, a cluster display, a
-- brazier, an idol, a banner, a fire, a crate, a plagued crate and a brazier, named after
-- what each riddle asks the player to find.
--
-- The objective of every quest is the cache, objective type 2 (gameobject). The module
-- completes the quest when the cache is opened, so the objective row is what the quest log
-- shows rather than what the core credits.
"""


def quest_rows():
    rows = []
    for hunt in HUNTS:
        index, name, riddle = hunt[0], hunt[1], hunt[2]
        quest = {
            "id": QUEST_FIRST + index - 1,
            "title": name,
            "log": "Find the cache and open it.",
            "description": "{} $B$BThe riddle is the only direction the steward will give. "
                           "The cache is somewhere in the neighbourhood, and it opens for "
                           "the player holding the riddle.".format(riddle),
            "completion": "The cache is open and the piece inside is yours.",
            "money": 0,
            "next": 0,
        }

        values = []
        for column in build_quests.COLUMNS:
            if column == "ID":
                values.append(str(quest["id"]))
            elif column == "RewardNextQuest":
                values.append("0")
            elif column == "RewardMoney":
                values.append("0")
            elif column == "LogTitle":
                values.append(build_quests.quote(quest["title"]))
            elif column == "LogDescription":
                values.append(build_quests.quote(quest["log"]))
            elif column == "QuestDescription":
                values.append(build_quests.quote(quest["description"]))
            elif column == "QuestCompletionLog":
                values.append(build_quests.quote(quest["completion"]))
            elif column in build_quests.TEXT:
                values.append(build_quests.quote(build_quests.STR_DEFAULT))
            else:
                values.append(str(build_quests.SET.get(column, build_quests.INT_DEFAULT)))
        rows.append("({})".format(", ".join(values)))
    return rows


def decor_rows(draft, base_id, with_item):
    rows = []
    for hunt in HUNTS:
        index = hunt[0]
        values = [str(base_id + index - 1), build_quests.quote(hunt[3]), str(hunt[4])]
        if with_item:
            values.append("0")
        values += ["1", "3", "2", build_quests.quote("Accents"), "4", str(index), "0", "0", "3", "0.5", "3", "0"]
        rows.append("({})".format(", ".join(values)))
    return rows


def hunt_rows(base_id):
    rows = []
    for hunt in HUNTS:
        index, name, riddle = hunt[0], hunt[1], hunt[2]
        rows.append("({}, {}, {}, {}, {}, {}, 0, 0, 0, 3)".format(
            index, build_quests.quote(name), build_quests.quote(riddle),
            QUEST_FIRST + index - 1, base_id + index - 1, hunt[6]))
    return rows


def objective_rows():
    rows = []
    for hunt in HUNTS:
        index = hunt[0]
        rows.append("({}, {}, 2, 1, 0, {}, 1, 0, 0, 0, NULL, 35662)".format(
            OBJECTIVE_FIRST + index - 1, QUEST_FIRST + index - 1, hunt[6]))
    return rows


def decor_columns(with_item):
    columns = ["id", "name", "gameobject_entry"]
    if with_item:
        columns.append("item_entry")
    columns += ["budget_cost", "surface", "placement", "category", "source_type",
                "source_id", "price", "currency", "faction_mask", "scale_min",
                "scale_max", "flags"]
    return columns


def build():
    for draft, base_id in DECOR_RANGES.items():
        with_item = draft == "midnight-port"
        decor_columns_ = decor_columns(with_item)
        low, high = base_id, base_id + len(HUNTS) - 1

        body = (HEADER
                + "\nDELETE FROM `housing_decor` WHERE `id` BETWEEN {} AND {};\n".format(low, high)
                + "INSERT INTO `housing_decor` ({}) VALUES\n".format(
                    ", ".join("`{}`".format(c) for c in decor_columns_))
                + ",\n".join(decor_rows(draft, base_id, with_item)) + ";\n"
                + "\nDELETE FROM `housing_hunt` WHERE `id` BETWEEN 1 AND {};\n".format(len(HUNTS))
                + "INSERT INTO `housing_hunt` ({}) VALUES\n".format(
                    ", ".join("`{}`".format(c) for c in HUNT_COLUMNS))
                + ",\n".join(hunt_rows(base_id)) + ";\n"
                + "\nDELETE FROM `quest_objectives` WHERE `QuestID` BETWEEN {} AND {};\n".format(
                    QUEST_FIRST, QUEST_FIRST + len(HUNTS) - 1)
                + "INSERT INTO `quest_objectives` (`ID`, `QuestID`, `Type`, `Order`, "
                  "`StorageIndex`, `ObjectID`, `Amount`, `Flags`, `Flags2`, "
                  "`ProgressBarWeight`, `Description`, `VerifiedBuild`) VALUES\n"
                + ",\n".join(objective_rows()) + ";\n"
                + "\nDELETE FROM `quest_template` WHERE `ID` BETWEEN {} AND {};\n".format(
                    QUEST_FIRST, QUEST_FIRST + len(HUNTS) - 1)
                + "INSERT INTO `quest_template` ({}) VALUES\n".format(
                    ", ".join("`{}`".format(c) for c in build_quests.COLUMNS))
                + ",\n".join(quest_rows()) + ";\n")

        path = os.path.join(DRAFTS, draft, "sql", "world", "08_hunts.sql")
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(body)

        print("wrote {} ({} hunts, {} quests)".format(
            os.path.relpath(path, HERE), len(HUNTS), len(HUNTS)))


if __name__ == "__main__":
    build()
